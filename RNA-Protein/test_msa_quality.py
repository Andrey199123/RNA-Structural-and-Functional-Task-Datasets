def assess_msa_quality(msa_array, rna_id="unknown"):
    """
    Assess the quality of an MSA
    
    Returns quality metrics dictionary
    """
    if len(msa_array) == 0:
        return {
            'depth': 0,
            'quality': 'empty',
            'score': 0.0
        }
    
    n_seq, length = msa_array.shape
    
    # 1. Depth score (more sequences = better, up to a point)
    depth_score = min(n_seq / 50.0, 1.0)  # Optimal around 50+ sequences
    
    # 2. Diversity score (sequences should be different)
    if n_seq > 1:
        query = msa_array[0]
        identities = []
        for i in range(1, min(n_seq, 20)):  # Check first 20
            mask = (query < 4) & (msa_array[i] < 4)
            if mask.sum() > 0:
                identity = (query[mask] == msa_array[i][mask]).sum() / mask.sum()
                identities.append(identity)
        
        if identities:
            avg_identity = np.mean(identities)
            # Good diversity: 40-80% identity
            if 0.4 <= avg_identity <= 0.8:
                diversity_score = 1.0
            elif avg_identity < 0.4:
                diversity_score = 0.7  # Too diverse, might be noise
            else:
                diversity_score = 0.3  # Too similar, redundant
        else:
            diversity_score = 0.0
    else:
        diversity_score = 0.0
    
    # 3. Conservation pattern (should have both conserved and variable positions)
    conservation = compute_conservation_map(msa_array)
    highly_conserved = (conservation > 0.8).sum()
    variable = (conservation < 0.5).sum()
    
    if highly_conserved > 0 and variable > 0:
        conservation_score = 1.0
    elif highly_conserved > 0 or variable > 0:
        conservation_score = 0.5
    else:
        conservation_score = 0.0

    # 4. Coevolution signal (should have some pairwise correlations)
    if n_seq >= 5:
        coevolution = compute_coevolution_map(msa_array, method="mi")
        # Check for non-zero coevolution signals
        np.fill_diagonal(coevolution, 0)
        strong_signals = (coevolution > 0.1).sum()
        coevolution_score = min(strong_signals / (length * 2), 1.0)
    else:
        coevolution_score = 0.0
    
    # 5. Gap content (too many gaps = poor alignment)
    gap_fraction = (msa_array == 4).sum() / msa_array.size
    if gap_fraction < 0.3:
        gap_score = 1.0
    elif gap_fraction < 0.5:
        gap_score = 0.7
    else:
        gap_score = 0.3
    
    # Overall quality score (weighted average)
    weights = {
        'depth': 0.3,
        'diversity': 0.2,
        'conservation': 0.2,
        'coevolution': 0.2,
        'gaps': 0.1
    }
    
    overall_score = (
        depth_score * weights['depth'] +
        diversity_score * weights['diversity'] +
        conservation_score * weights['conservation'] +
        coevolution_score * weights['coevolution'] +
        gap_score * weights['gaps']
    )
    
    # Quality rating
    if overall_score >= 0.8:
        quality = "excellent"
    elif overall_score >= 0.6:
        quality = "good"
    elif overall_score >= 0.4:
        quality = "fair"
    elif overall_score >= 0.2:
        quality = "poor"
    else:
        quality = "very_poor"
    
    return {
        'depth': n_seq,
        'avg_identity': np.mean(identities) if identities else 0.0,
        'conservation_score': conservation_score,
        'coevolution_score': coevolution_score,
        'gap_fraction': gap_fraction,
        'overall_score': overall_score,
        'quality': quality,
        'details': {
            'depth_score': depth_score,
            'diversity_score': diversity_score,
            'gap_score': gap_score,
            'highly_conserved_positions': int(highly_conserved),
            'variable_positions': int(variable)
        }
    }


def test_strategy_comparison():
    """
    Test and compare all four strategies on the same RNA
    """
    print("=" * 70)
    print("Test: Strategy Comparison")
    print("=" * 70)
    
    # Use a real tRNA sequence (known structure, should have good MSAs)
    test_rna = RNASequence(
        id="tRNA_Phe",
        sequence="GCGGAUUUAGCUCAGUUGGGAGAGCGCCAGACUGAAGAUCUGGAGGUCCUGUGUUCGAUCCACAGAAUUCGCACCA",
        length=76,
        description="tRNA-Phe (should match Rfam)"
    )
    
    print(f"\nTest RNA: {test_rna.id}")
    print(f"Length: {test_rna.length} nt")
    print(f"Sequence: {test_rna.sequence[:50]}...")
    
    with tempfile.TemporaryDirectory() as tmpdir:
        pipeline = RNAMSAPipeline(output_dir=Path(tmpdir), n_cpu=2)
        
        strategies_to_test = [
            RNAStrategy.SINGLE_SEQUENCE,  # Always works
            # RNAStrategy.INFERNAL_RFAM,  # Requires Rfam DB
            # RNAStrategy.RNACMAP_STYLE,  # Requires sequence DB
        ]
        
        results = {}
        
        for strategy in strategies_to_test:
            print(f"\n{'='*70}")
            print(f"Testing: {strategy.value}")
            print(f"{'='*70}")
            
            try:
                result = pipeline.process_rna(test_rna, strategy=strategy, force_strategy=True)
                
                if result['success']:
                    print(f"✓ Strategy succeeded")
                    print(f"  MSA depth: {result.get('msa_depth', 0)}")
                    
                    # Assess quality if we have structure
                    if 'structure' in result:
                        print(f"  Method: {result['structure'].get('method', 'unknown')}")
                        quality = {'quality': 'single_sequence', 'overall_score': 0.3}
                    else:
                        quality = {'quality': 'unknown', 'overall_score': 0.0}
                    
                    results[strategy.value] = {
                        'success': True,
                        'quality': quality,
                        'msa_depth': result.get('msa_depth', 0)
                    }
                else:
                    print(f"✗ Strategy failed: {result.get('error', 'unknown')}")
                    results[strategy.value] = {'success': False}
                    
            except Exception as e:
                print(f"✗ Exception: {e}")
                results[strategy.value] = {'success': False, 'error': str(e)}
        
        # Summary
        print(f"\n{'='*70}")
        print("Strategy Comparison Summary")
        print(f"{'='*70}")
        
        for strategy, result in results.items():
            if result['success']:
                quality = result['quality']
                print(f"\n{strategy}:")
                print(f"  Quality: {quality['quality']}")
                print(f"  Score: {quality['overall_score']:.2f}")
                print(f"  MSA depth: {result['msa_depth']}")
            else:
                print(f"\n{strategy}: FAILED")
        
        return results


